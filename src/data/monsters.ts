export const HYBRID_SPECIES_IDS = TREE_SPECIES_IDS;

export function getSpecies(id: SpeciesId): SpeciesDef {
  return SPECIES[id];
}

/** A espécie pode existir no nível dado (puro: 1..5; árvore: nível fixo). */
export function speciesAllowsLevel(id: SpeciesId, level: number): boolean {
  const def = SPECIES[id];
  return level >= def.levelMin && level <= def.levelMax;
}
